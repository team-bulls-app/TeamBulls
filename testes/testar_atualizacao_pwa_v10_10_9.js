'use strict';
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
function assert(condition,message){if(!condition)throw new Error(message);}

const html=read('index.html');
const core=read('app_v10_10_9_core.js');
const updater=read('update_v10_10_9.js');
const worker=read('sw.js');
const bridge=read('sw_47.js');
const manifest=JSON.parse(read('manifest.json'));
const version=JSON.parse(read('version.json'));
const BUILD=Number(version.build);

assert(version.version==='10.10.9','version.json incorreto');
assert(version.build===BUILD,'version.json não informa o build atual');
assert(manifest.start_url==='./index.html','start_url ainda está preso a uma versão antiga');
assert(manifest.scope==='./','scope do manifesto incorreto');
assert(html.includes(`update_v10_10_9.js?v=10.10.9&b=${BUILD}`),'gerenciador de atualização não é carregado');
assert(html.includes('manifest.json?v=10.10.9'),'manifesto estável não é utilizado');
assert(html.includes('modules/v107-core.js?v=10.10.9'),'módulos estáveis não possuem bust de versão');
assert(!core.includes("serviceWorker.register('sw_47.js'"),'núcleo ainda registra o worker obsoleto');
assert(updater.includes(`const CURRENT_BUILD=${BUILD}`),'atualizador não conhece o build atual');
assert(updater.includes('navigator.serviceWorker.register(`./sw.js?v=${encodeURIComponent(CURRENT_VERSION)}&b=${CURRENT_BUILD}`'),'worker estável não é registrado com build');
assert(updater.includes("fetch(`${VERSION_URL}?t=${Date.now()}`"),'verificação de versão não evita cache HTTP');
assert(updater.includes('sessionStorage.setItem(UPDATE_RELOAD_KEY,releaseKey(target))'),'recarga de atualização não grava versão + build');
assert(updater.includes("const APPLIED_RELEASE_KEY='team-bulls-applied-release'"),'release aplicada não possui memória persistente para encerrar o aviso após recarga');
assert(updater.includes('const newer=compareRelease(info)>0&&!isReleaseApplied(info)'),'aviso volta a aparecer para a mesma revisão já aplicada');
assert(updater.includes('if(updated&&stored===targetKey){rememberAppliedRelease(target);'),'conclusão não registra a revisão efetivamente preparada');
assert(updater.includes("success:true,visible:true"),'notificação de sucesso não é preservada enquanto a versão atualiza');
assert(html.includes(`update_v10_10_9.js?v=10.10.9&b=${BUILD}`),'script do atualizador não invalida cache ao mudar o build');
assert(updater.includes('function compareRelease(info)'),'atualizador não compara versão + build');
assert(updater.includes('function safeForAutomaticHotfix()'),'hotfix automático não possui gate de tela segura');
assert(updater.includes("if(screen!=='screen-auth')return false"),'hotfix poderia recarregar durante uso ativo');
assert(updater.includes("TB?.flushDrafts?.()"),'rascunhos não são salvos antes da atualização');
assert(updater.includes("manualCheck:()=>checkForUpdates"),'verificação manual não está exposta');
assert(worker.includes("const APP_VERSION='10.10.9'"),'versão do Service Worker incorreta');
assert(worker.includes(`const BUILD_REVISION=${BUILD}`),'Service Worker não anuncia build');
assert(worker.includes("request.mode==='navigate'"),'navegação não é interceptada');
assert(worker.includes('event.respondWith(navigationNetworkFirst(request,event))'),'navegação precisa priorizar o HTML atualizado com timeout limitado.');
const navigationTimeout=Number(worker.match(/const NAVIGATION_REFRESH_TIMEOUT_MS=(\d+)/)?.[1]||0);
assert(navigationTimeout>0&&navigationTimeout<=5000,'Atualização de HTML não pode bloquear a abertura indefinidamente.');
assert(worker.includes('if(cached)return secureResponse(cached.clone(),{html:true})'),'navegação offline precisa recuperar o HTML em cache.');
assert(!worker.includes('navigationCacheFirst(request,event)'),'estratégia antiga não deve substituir atualização de HTML com fallback offline.');
assert(worker.includes("relativePath==='/version.json'"),'version.json não recebe estratégia fresca');
const versionedRoute=worker.indexOf("if(VERSIONED_PATH_PATTERN.test(fileName)||url.searchParams.has('v'))");
const mutableRoute=worker.indexOf('if(MUTABLE_PATHS.has(relativePath))');
assert(versionedRoute>=0&&mutableRoute>=0&&mutableRoute<versionedRoute,'arquivos mutáveis devem usar network-first antes do cache-first genérico por ?v=.');
assert(worker.includes("await self.clients.claim()"),'novo worker não assume clientes');
assert(worker.includes("await self.skipWaiting()"),'novo worker não ativa imediatamente');
assert(worker.includes("key!==AUDIO_CACHE_NAME"),'limpeza de cache pode apagar áudio desnecessariamente');
assert(worker.includes("type:'TEAM_BULLS_SW_ACTIVATED',version:APP_VERSION,build:BUILD_REVISION"),'worker não comunica o build ativado');
assert(bridge===worker,'Service Workers principal e legado precisam permanecer idênticos.');
console.log('APROVADO: atualização build-aware, navegação com timeout/fallback offline, assets versionados em cache-first e Service Workers coerentes.');
